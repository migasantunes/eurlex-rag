"""The results table, generated from the result files.

Numbers in the README are copied from ``results/table.md``, and that file is
built only from ``results/*.json`` by this module. Nobody types a metric by hand
(CLAUDE.md rule 1).

Each R@5 cell shows the mean and the 95% interval, ``0.62 [0.50, 0.73]``, so a
reader sees at once whether two rungs really differ or sit inside each other's
noise.
"""

from __future__ import annotations

from pathlib import Path

from eurlex_rag.eval.results import load_results

TABLE_LANGS = ("en", "pt", "fr")
_HEADER = "| Rung | Split | R@5 EN | R@5 PT | R@5 FR | MRR@10 | nDCG@10 | p95 ms | n |"
_RULE = "|---|---|---|---|---|---|---|---|---|"
DASH = "–"


def _with_ci(summary: dict | None) -> str:
    """``0.62 [0.50, 0.73]`` from a ``{"mean", "low", "high"}`` dict."""
    if not summary:
        return DASH
    return f"{summary['mean']:.2f} [{summary['low']:.2f}, {summary['high']:.2f}]"


def _plain(summary: dict | None) -> str:
    return f"{summary['mean']:.2f}" if summary else DASH


def _row(result: dict) -> str:
    evaluation = result.get("evaluation", {})
    by_lang = evaluation.get("by_lang", {})
    pooled = evaluation.get("pooled", {})
    p95 = evaluation.get("latency_ms", {}).get("p95")
    cells = [
        result.get("rung", "?"),
        result.get("split", "?"),
        *(_with_ci(by_lang.get(lang, {}).get("recall@5")) for lang in TABLE_LANGS),
        _plain(pooled.get("mrr@10")),  # pooled over languages, per question
        _plain(pooled.get("ndcg@10")),
        DASH if p95 is None else f"{p95:.1f}",
        str(pooled.get("n", 0)),  # number of questions scored
    ]
    return "| " + " | ".join(cells) + " |"


def build_table(results: list[dict]) -> str:
    """Markdown table, one row per result file, sorted by rung then split.

    MRR@10 and nDCG@10 are pooled over the query languages (each question
    counts once); ``n`` is the number of answerable questions scored.
    """
    ordered = sorted(results, key=lambda r: (r.get("rung", ""), r.get("split", "")))
    lines = [_HEADER, _RULE, *(_row(result) for result in ordered)]
    return "\n".join(lines) + "\n"


def write_report(results_dir: Path | str) -> Path:
    """Write ``<results_dir>/table.md`` from the result files and return its path."""
    results_dir = Path(results_dir)
    results = load_results(results_dir)
    header = (
        "<!-- Generated by `eurlex report` from results/*.json. Do not edit by hand. -->\n\n"
        "Dev numbers are for choosing settings; test numbers are the ones to quote.\n"
        "R@5 cells show the mean and its 95% bootstrap interval. "
        "MRR@10 and nDCG@10 are pooled over languages; n is the number of questions.\n\n"
    )
    path = results_dir / "table.md"
    results_dir.mkdir(parents=True, exist_ok=True)
    path.write_text(header + build_table(results), encoding="utf-8")
    return path
